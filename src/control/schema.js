const field = (section, key, label, type, value, extra = {}) => ({ section, key, label, type, value, ...extra })
const num = (section, key, label, value, extra) => field(section, key, label, 'number', value, extra)
const text = (section, key, label, value, extra) => field(section, key, label, 'text', value, extra)
const tog = (section, key, label, value, extra) => field(section, key, label, 'toggle', value, extra)
const sel = (section, key, label, value, options, extra) => field(section, key, label, 'select', value, { options, ...extra })
const area = (section, key, label, value, extra) => field(section, key, label, 'textarea', value, extra)
const secret = (section, key, label) => field(section, key, label, 'secret', '')

